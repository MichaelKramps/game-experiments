#!/usr/bin/env python3
"""Build guesses.js (the extra words accepted as guesses) from SCOWL (american spelling).

Usage: python3 build-guesses.py /path/to/scowl-2020.12.07

Accepted guesses: every 5-letter word in SCOWL up to size 50, plurals and past
tenses included, minus offensive words. The answers (words.js) are always
accepted too; only the words not already in words.js are written out.
"""
import os, re, sys

SCOWL_VERSION = '2020.12.07'
MAX_SIZE = 50
SIZES = [10, 20, 35, 40, 50, 55, 60, 70, 80, 95]
CATEGORIES = ['english-words', 'american-words']
TABOO_FILES = ['offensive.1', 'offensive.2', 'profane.1', 'profane.3']
# Slurs and vulgarities SCOWL's taboo files miss (5-letter ones from letter-groups' list).
MANUAL_TABOO = set('''
dykes homos spics kikes darky dagos twats honky negro squaw limey sluts whore bitch porno
'''.split())

root = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))

def read(path):
    with open(path, encoding='latin-1') as f:
        return [w.strip() for w in f if w.strip()]

taboo = set(MANUAL_TABOO)
for name in TABOO_FILES:
    taboo.update(w.lower() for w in read(os.path.join(root, 'misc', name)))

words = set()
for size in SIZES:
    if size > MAX_SIZE:
        break
    for cat in CATEGORIES:
        path = os.path.join(root, 'final', f'{cat}.{size}')
        if os.path.exists(path):
            words.update(w for w in read(path) if re.fullmatch(r'[a-z]{5}', w))
words -= taboo

with open(os.path.join(here, '..', 'words.js')) as f:
    answers = set(re.findall(r"'([a-z]{5})'", f.read()))
missing = answers - words
if missing:
    print('note: answers not in SCOWL list (still accepted):', sorted(missing))
extra = sorted(words - answers)

with open(os.path.join(here, '..', 'guesses.js'), 'w') as f:
    f.write('// Generated by tools/build-guesses.py from SCOWL %s (american, up to size %d). Do not edit by hand.\n' % (SCOWL_VERSION, MAX_SIZE))
    f.write('// Word list: Copyright 2000-2018 Kevin Atkinson and others (SCOWL, permissive license).\n')
    f.write('// Extra accepted guesses; the game also accepts every word in words.js.\n')
    f.write("const EXTRA_GUESS_WORDS = '%s'.split(' ');\n" % ' '.join(extra))
print(len(answers), 'answers +', len(extra), 'extra =', len(answers) + len(extra), 'accepted guesses')
