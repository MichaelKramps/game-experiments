#!/usr/bin/env python3
"""Build words.js from SCOWL (american spelling).

Usage: python3 build-words.py /path/to/scowl-2020.12.07

Answer list: SCOWL size 35. Validation list: SCOWL up to size 70.
Seeds depend on these lists, so bump WORDS_VERSION whenever the output changes.
"""
import os, re, sys

SCOWL_VERSION = '2020.12.07'
SIZES = [10, 20, 35, 40, 50, 55, 60, 70]
CATEGORIES = ['english-words', 'american-words']
TABOO_FILES = ['offensive.1', 'offensive.2', 'profane.1', 'profane.3']
# Manual pass, part 1: slurs and vulgarities SCOWL's taboo files miss. Removed from both lists.
MANUAL_TABOO = set('''
wog wogs dyke dykes fag fags faggot faggots homo homos spic spics kike kikes darky darkie darkies
dago dagos twat twats dickhead honky honkies negro negroes squaw squaws gyp gyps gypped redskin redskins
limey limeys wetback wetbacks retard retards slut sluts slutty whore whores bitch bitches bitchy
porn porno spaz
'''.split())
# Manual pass, part 2: real words that can still be typed but should never appear as a
# hint or reference answer (double meanings, slurs-as-homonyms, sexual or violent terms).
NOT_ANSWERS = set('''
cock cocks cocky chink chinks prick pricks tit tits midget midgets fairy fairies retarded
bastard bastards damn damned horny semen penis penises vagina vaginas anal anus rape raped rapes
rapist rapists molest molested incest orgasm orgasms erection erections sperm sexy gypsy gypsies
mick micks gringo gringos spastic pedophile masturbate nazi nazis
'''.split())

root = sys.argv[1]

def read(path):
    with open(path, encoding='latin-1') as f:
        return [w.strip() for w in f if w.strip()]

def has_double(w):
    return any(a == b for a, b in zip(w, w[1:]))

taboo = set(MANUAL_TABOO)
for name in TABOO_FILES:
    taboo.update(w.lower() for w in read(os.path.join(root, 'misc', name)))

def collect(max_size):
    out = set()
    for size in SIZES:
        if size > max_size:
            break
        for cat in CATEGORIES:
            path = os.path.join(root, 'final', f'{cat}.{size}')
            if os.path.exists(path):
                out.update(read(path))
    # Lowercase a-z only drops proper nouns, abbreviations and possessives.
    return sorted(w for w in out
                  if re.fullmatch(r'[a-z]{3,}', w) and not has_double(w) and w not in taboo)

answers = [w for w in collect(35) if w not in NOT_ANSWERS]
valid = collect(70)
assert set(answers) <= set(valid)

here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, '..', 'words.js'), 'w') as f:
    f.write('// Generated by tools/build-words.py from SCOWL %s (american). Do not edit by hand.\n' % SCOWL_VERSION)
    f.write('// Word lists: Copyright 2000-2018 Kevin Atkinson and others; see the About line in game.\n')
    f.write("const WORDS_VERSION = 'scowl-%s-v1';\n" % SCOWL_VERSION)
    f.write("const ANSWER_WORDS = '%s'.split(' ');\n" % ' '.join(answers))
    # Only the extra words are stored; the game unions them with ANSWER_WORDS.
    extra = sorted(set(valid) - set(answers))
    f.write("const EXTRA_VALID_WORDS = '%s'.split(' ');\n" % ' '.join(extra))
print(len(answers), 'answer words,', len(valid), 'valid words')
